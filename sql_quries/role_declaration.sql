
CREATE ROLE IF NOT EXISTS TRACE_METADATA_ROLE;

CREATE USER IF NOT EXISTS TRACE_METADATA_READER
    TYPE = SERVICE
    DEFAULT_ROLE = TRACE_METADATA_ROLE;

GRANT ROLE TRACE_METADATA_ROLE
TO USER TRACE_METADATA_READER;

GRANT USAGE ON DATABASE NOVAMART_DB
TO ROLE TRACE_METADATA_ROLE;

GRANT USAGE ON ALL SCHEMAS
IN DATABASE NOVAMART_DB
TO ROLE TRACE_METADATA_ROLE;

GRANT REFERENCES ON ALL TABLES
IN DATABASE NOVAMART_DB
TO ROLE TRACE_METADATA_ROLE;

GRANT REFERENCES ON ALL VIEWS
IN DATABASE NOVAMART_DB
TO ROLE TRACE_METADATA_ROLE;


ALTER USER TRACE_METADATA_READER
SET RSA_PUBLIC_KEY = '<SNOWFLAKE_RSA_PUBLIC_KEY>';


DESCRIBE USER TRACE_METADATA_READER;


SELECT
    CURRENT_ORGANIZATION_NAME() AS ORGANIZATION_NAME,
    CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME,
    CURRENT_REGION() AS REGION;


