-- NovaMart step 5C: ANALYTICS views. Matches the six NovaMart/analytics/*.csv baseline references.
-- Run after 03_staging_views.sql and 04_curated_views.sql.
-- Currency: INR. "Gross sales" here is recognized order NET_AMOUNT before processed refunds, excluding tax.
-- No direct joins to payments or shipment events in these aggregates: they could multiply rows.
USE DATABASE NOVAMART_DB;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE VIEW NOVAMART_DB.ANALYTICS.DAILY_SALES AS
SELECT
    SALES_DATE,
    COUNT(*) AS RECOGNIZED_ORDERS,
    SUM(HAS_PROCESSED_REFUND) AS ORDERS_WITH_PROCESSED_REFUNDS,
    SUM(GROSS_SALES_EX_TAX_INR)::NUMBER(20,2) AS GROSS_SALES_EX_TAX_INR,
    SUM(PROCESSED_REFUNDS_EX_TAX_INR)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    SUM(NET_REVENUE_INR)::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS
GROUP BY SALES_DATE;

CREATE OR REPLACE VIEW NOVAMART_DB.ANALYTICS.MONTHLY_REVENUE AS
SELECT
    TO_CHAR(SALES_MONTH, 'YYYY-MM') AS SALES_MONTH,
    COUNT(*) AS RECOGNIZED_ORDERS,
    SUM(HAS_PROCESSED_REFUND) AS ORDERS_WITH_PROCESSED_REFUNDS,
    SUM(GROSS_SALES_EX_TAX_INR)::NUMBER(20,2) AS GROSS_SALES_EX_TAX_INR,
    SUM(PROCESSED_REFUNDS_EX_TAX_INR)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    SUM(NET_REVENUE_INR)::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS
GROUP BY SALES_MONTH;

CREATE OR REPLACE VIEW NOVAMART_DB.ANALYTICS.STORE_PERFORMANCE AS
SELECT
    STORE_ID,
    COUNT(*) AS RECOGNIZED_ORDERS,
    SUM(HAS_PROCESSED_REFUND) AS ORDERS_WITH_PROCESSED_REFUNDS,
    SUM(GROSS_SALES_EX_TAX_INR)::NUMBER(20,2) AS GROSS_SALES_EX_TAX_INR,
    SUM(PROCESSED_REFUNDS_EX_TAX_INR)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    SUM(NET_REVENUE_INR)::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS
GROUP BY STORE_ID;

CREATE OR REPLACE VIEW NOVAMART_DB.ANALYTICS.CHANNEL_PERFORMANCE AS
SELECT
    ORDER_CHANNEL,
    COUNT(*) AS RECOGNIZED_ORDERS,
    SUM(HAS_PROCESSED_REFUND) AS ORDERS_WITH_PROCESSED_REFUNDS,
    SUM(GROSS_SALES_EX_TAX_INR)::NUMBER(20,2) AS GROSS_SALES_EX_TAX_INR,
    SUM(PROCESSED_REFUNDS_EX_TAX_INR)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    SUM(NET_REVENUE_INR)::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS
GROUP BY ORDER_CHANNEL;

CREATE OR REPLACE VIEW NOVAMART_DB.ANALYTICS.CUSTOMER_VALUE AS
SELECT
    CUSTOMER_ID,
    COUNT(*) AS RECOGNIZED_ORDERS,
    SUM(GROSS_SALES_EX_TAX_INR)::NUMBER(20,2) AS GROSS_SALES_EX_TAX_INR,
    SUM(NET_REVENUE_INR)::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS
WHERE CUSTOMER_ID IS NOT NULL
GROUP BY CUSTOMER_ID;

CREATE OR REPLACE VIEW NOVAMART_DB.ANALYTICS.CATEGORY_PERFORMANCE AS
SELECT
    CATEGORY_ID,
    COUNT(*) AS RECOGNIZED_ORDER_LINES,
    SUM(QUANTITY) AS UNITS_SOLD,
    SUM(GROSS_SALES_EX_TAX_INR)::NUMBER(20,2) AS GROSS_SALES_EX_TAX_INR,
    SUM(PROCESSED_REFUNDS_EX_TAX_INR)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    SUM(NET_REVENUE_INR)::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDER_ITEMS
GROUP BY CATEGORY_ID;
