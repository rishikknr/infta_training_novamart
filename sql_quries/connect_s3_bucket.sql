


CREATE STORAGE INTEGRATION NOVAMART_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<AWS_ACCOUNT_ID>:role/NovaMartSnowflakeReadOnlyRole'
  STORAGE_ALLOWED_LOCATIONS = (
    's3://novamart-trace-test-space/novamart/baseline/'
  );

  
DESC INTEGRATION NOVAMART_S3_INT;



CREATE STAGE IF NOT EXISTS NOVAMART_DB.RAW.NOVAMART_S3_STAGE
  URL = 's3://novamart-trace-test-space/novamart/baseline/'
  STORAGE_INTEGRATION = NOVAMART_S3_INT
  FILE_FORMAT = NOVAMART_DB.RAW.NOVAMART_CSV_FORMAT;


LIST @NOVAMART_DB.RAW.NOVAMART_S3_STAGE;


DESC STAGE NOVAMART_DB.RAW.NOVAMART_S3_STAGE;


DESC INTEGRATION NOVAMART_S3_INT;

LIST @NOVAMART_DB.RAW.NOVAMART_S3_STAGE;

DESC STAGE NOVAMART_DB.RAW.NOVAMART_S3_STAGE;


ALTER STORAGE INTEGRATION NOVAMART_S3_INT
SET STORAGE_AWS_ROLE_ARN =
'arn:aws:iam::<AWS_ACCOUNT_ID>:role/NovaMartSnowflakeReadOnlyRoleV2';


DESC INTEGRATION NOVAMART_S3_INT;


LIST @NOVAMART_DB.RAW.NOVAMART_S3_STAGE;



CREATE STAGE NOVAMART_DB.RAW.NOVAMART_S3_KEY_STAGE
  URL = 's3://novamart-trace-test-space/novamart/baseline/'
  CREDENTIALS = (
    AWS_KEY_ID = '<AWS_ACCESS_KEY_ID>'
    AWS_SECRET_KEY = '<AWS_SECRET_ACCESS_KEY>'
  )
  FILE_FORMAT = NOVAMART_DB.RAW.NOVAMART_CSV_FORMAT;



LIST @NOVAMART_DB.RAW.NOVAMART_S3_KEY_STAGE;