-- NovaMart step 5B: CURATED business logic.
-- Revenue is NET_AMOUNT excluding tax, not ORDER_TOTAL. Only delivered/returned/partially-returned orders recognized.
-- Only PROCESSED refunds are deducted. Refunds are assigned to ORIGINAL order date.
-- Be aware this is an intentionally simplified synthetic business definition, not a universal accounting policy.
USE DATABASE NOVAMART_DB;
USE SCHEMA CURATED;

-- One row per recognized order. Aggregate refunds BEFORE joining to avoid multiplicative row explosion.
CREATE OR REPLACE VIEW NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS AS
WITH processed_refunds_by_order AS (
    SELECT
        ORDER_ID,
        COUNT(*) AS PROCESSED_REFUND_COUNT,
        SUM(REFUND_NET_AMOUNT) AS PROCESSED_REFUNDS_EX_TAX_INR
    FROM NOVAMART_DB.STAGING.STG_FACT_REFUNDS
    WHERE REFUND_STATUS = 'PROCESSED'
    GROUP BY ORDER_ID
)
SELECT
    o.ORDER_ID,
    o.CUSTOMER_ID,
    o.STORE_ID,
    o.ORDER_CHANNEL,
    o.ORDER_STATUS,
    o.PAYMENT_STATUS,
    o.CURRENCY,
    o.ORDER_DATE,
    TO_DATE(o.ORDER_DATE) AS SALES_DATE,
    DATE_TRUNC('MONTH', TO_DATE(o.ORDER_DATE))::DATE AS SALES_MONTH,
    o.GROSS_AMOUNT AS ORDER_GROSS_BEFORE_DISCOUNTS_EX_TAX_INR,
    o.DISCOUNT_AMOUNT AS ORDER_DISCOUNTS_EX_TAX_INR,
    o.NET_AMOUNT AS GROSS_SALES_EX_TAX_INR,
    o.TAX_AMOUNT AS TAX_AMOUNT_INR,
    o.SHIPPING_FEE AS SHIPPING_FEE_INR,
    o.ORDER_TOTAL AS ORDER_TOTAL_INCL_TAX_AND_SHIPPING_INR,
    COALESCE(r.PROCESSED_REFUND_COUNT, 0) AS PROCESSED_REFUND_COUNT,
    IFF(COALESCE(r.PROCESSED_REFUND_COUNT, 0) > 0, 1, 0) AS HAS_PROCESSED_REFUND,
    COALESCE(r.PROCESSED_REFUNDS_EX_TAX_INR, 0)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    (o.NET_AMOUNT - COALESCE(r.PROCESSED_REFUNDS_EX_TAX_INR, 0))::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.STAGING.STG_FACT_ORDERS o
LEFT JOIN processed_refunds_by_order r
    ON o.ORDER_ID = r.ORDER_ID
WHERE o.ORDER_STATUS IN ('DELIVERED', 'RETURNED', 'PARTIALLY_RETURNED');

-- One row per PROCESSED refund, mapped through the originating return to an order item.
-- This mapping is essential for category-level net revenue without double counting.
CREATE OR REPLACE VIEW NOVAMART_DB.CURATED.FCT_PROCESSED_REFUNDS AS
SELECT
    f.REFUND_ID,
    f.RETURN_ID,
    f.ORDER_ID,
    r.ORDER_ITEM_ID,
    r.RETURN_QUANTITY,
    f.REFUNDED_AT,
    o.SALES_DATE AS ORIGINAL_ORDER_DATE,
    f.REFUND_NET_AMOUNT AS REFUND_NET_AMOUNT_INR,
    f.REFUND_TAX_AMOUNT AS REFUND_TAX_AMOUNT_INR,
    f.REFUND_TOTAL AS REFUND_TOTAL_INR
FROM NOVAMART_DB.STAGING.STG_FACT_REFUNDS f
INNER JOIN NOVAMART_DB.STAGING.STG_FACT_RETURNS r
    ON f.RETURN_ID = r.RETURN_ID AND f.ORDER_ID = r.ORDER_ID
INNER JOIN NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS o
    ON f.ORDER_ID = o.ORDER_ID
WHERE f.REFUND_STATUS = 'PROCESSED';

-- One row per item in a recognized order, enriched with product category.
-- Aggregate processed refunds to item granularity before the join.
CREATE OR REPLACE VIEW NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDER_ITEMS AS
WITH refunds_by_item AS (
    SELECT
        ORDER_ITEM_ID,
        SUM(REFUND_NET_AMOUNT_INR) AS PROCESSED_REFUNDS_EX_TAX_INR
    FROM NOVAMART_DB.CURATED.FCT_PROCESSED_REFUNDS
    GROUP BY ORDER_ITEM_ID
)
SELECT
    i.ORDER_ITEM_ID,
    i.ORDER_ID,
    o.SALES_DATE,
    o.CUSTOMER_ID,
    o.STORE_ID,
    o.ORDER_CHANNEL,
    i.PRODUCT_ID,
    p.CATEGORY_ID,
    p.CATEGORY_NAME,
    i.ITEM_STATUS,
    i.QUANTITY,
    i.UNIT_PRICE,
    i.NET_AMOUNT AS GROSS_SALES_EX_TAX_INR,
    COALESCE(r.PROCESSED_REFUNDS_EX_TAX_INR, 0)::NUMBER(20,2) AS PROCESSED_REFUNDS_EX_TAX_INR,
    (i.NET_AMOUNT - COALESCE(r.PROCESSED_REFUNDS_EX_TAX_INR, 0))::NUMBER(20,2) AS NET_REVENUE_INR
FROM NOVAMART_DB.STAGING.STG_FACT_ORDER_ITEMS i
INNER JOIN NOVAMART_DB.CURATED.FCT_RECOGNIZED_ORDERS o
    ON i.ORDER_ID = o.ORDER_ID
INNER JOIN NOVAMART_DB.STAGING.STG_DIM_PRODUCTS p
    ON i.PRODUCT_ID = p.PRODUCT_ID
LEFT JOIN refunds_by_item r
    ON i.ORDER_ITEM_ID = r.ORDER_ITEM_ID;
