-- NovaMart step 5A: STAGING layer: typed, normalized views over 22 RAW datasets.
-- Run AFTER the baseline load has completed and verified.
-- Views are safe to recreate for this synthetic baseline; existing views of these names are replaced.
-- Intentionally use EXPLICIT columns (no SELECT *) for column-level lineage.
-- Snowflake RAW tables already hold correctly typed DATE, TIMESTAMP_TZ and NUMBER columns.
